/* Compiles the D3D11 test's shaders and prints them as a C header, so the test
 * doesn't depend on the d3dcompiler of the Wine it runs on.
 *
 * Build: x86_64-w64-mingw32-gcc -O2 -o shadergen.exe shadergen.c -ld3dcompiler_47
 * Run:   porta wine selftest-cx tests/shadergen.exe > tests/d3d11test_shaders.h
 */
#define COBJMACROS
#include <windows.h>
#include <d3dcompiler.h>
#include <stdio.h>

static const char shader_src[] =
    "float4 vs(uint id : SV_VertexID) : SV_Position\n"
    "{\n"
    "    float x = float(id == 1) * 0.7 - float(id == 2) * 0.7;\n"
    "    float y = float(id == 0) * 1.4 - 0.7;\n"
    "    return float4(x, y, 0.0, 1.0);\n"
    "}\n"
    "float4 ps(float4 pos : SV_Position) : SV_Target\n"
    "{\n"
    "    return float4(1.0, 0.5, 0.0, 1.0);\n"
    "}\n";

static int emit(const char *name, const char *entry, const char *target)
{
    ID3DBlob *code = NULL, *errors = NULL;
    const BYTE *bytes;
    SIZE_T i, size;

    if (FAILED(D3DCompile(shader_src, sizeof(shader_src) - 1, NULL, NULL, NULL, entry, target,
                          D3DCOMPILE_OPTIMIZATION_LEVEL3, 0, &code, &errors)))
    {
        fprintf(stderr, "%s: %s\n", entry, errors ? (const char *)ID3D10Blob_GetBufferPointer(errors) : "failed");
        return 0;
    }
    bytes = ID3D10Blob_GetBufferPointer(code);
    size = ID3D10Blob_GetBufferSize(code);
    printf("static const BYTE %s[] =\n{", name);
    for (i = 0; i < size; i++) printf("%s0x%02x,", i % 12 ? " " : "\n    ", bytes[i]);
    printf("\n};\n\n");
    return 1;
}

int main(void)
{
    printf("/* Generated by shadergen.exe from the shader source in shadergen.c, do not edit. */\n\n");
    return emit("vs_code", "vs", "vs_4_0") && emit("ps_code", "ps", "ps_4_0") ? 0 : 1;
}
